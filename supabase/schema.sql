-- equipDemo: equipment table, constraints and row-level security (RLS).
-- Run in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Safe to run more than once, and safe on an existing `equipment` table.

-- 1. Table ---------------------------------------------------------------
create table if not exists public.equipment (
  id             bigint generated by default as identity primary key,
  name           text           not null,
  price_per_hour numeric(10, 2) not null,
  created_at     timestamptz    not null default now()
);

-- If the table already existed without created_at, add it.
alter table public.equipment
  add column if not exists created_at timestamptz not null default now();

-- 2. Constraints -----------------------------------------------------------
-- The server enforces the same rules as the app, so a modified or bypassed
-- client still cannot store bad data. NOT VALID: existing rows are not
-- re-checked, new and updated rows are.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'equipment_name_length') then
    alter table public.equipment
      add constraint equipment_name_length
      check (char_length(btrim(name)) between 2 and 60) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'equipment_price_range') then
    alter table public.equipment
      add constraint equipment_price_range
      check (price_per_hour > 0 and price_per_hour <= 100000) not valid;
  end if;
end $$;

-- 3. Row-level security ---------------------------------------------------------
-- With RLS on, the publishable (anon) key can do ONLY what a policy allows.
alter table public.equipment enable row level security;

-- Anyone using the app may read equipment.
drop policy if exists "equipment_select_public" on public.equipment;
create policy "equipment_select_public"
  on public.equipment for select
  to anon, authenticated
  using (true);

-- Anyone using the app may add equipment (demo: there is no sign-in).
drop policy if exists "equipment_insert_public" on public.equipment;
create policy "equipment_insert_public"
  on public.equipment for insert
  to anon, authenticated
  with check (
    char_length(btrim(name)) between 2 and 60
    and price_per_hour > 0
    and price_per_hour <= 100000
  );

-- No UPDATE or DELETE policies: with RLS on, those operations are denied to
-- the publishable key. Only the dashboard / service role can change or remove rows.

-- 4. Table privileges -----------------------------------------------------------
-- RLS filters rows; these grants decide which operations are possible at all.
revoke all on public.equipment from anon, authenticated;
grant select, insert on public.equipment to anon, authenticated;
-- Needed only if `id` uses a serial sequence (identity columns don't need it).
do $$
declare
  seq text := pg_get_serial_sequence('public.equipment', 'id');
begin
  if seq is not null then
    execute format('grant usage, select on sequence %s to anon, authenticated', seq);
  end if;
end $$;
